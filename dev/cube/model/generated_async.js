// A JavaScript model that creates its cubes asynchronously.
asyncModule(async () => {
  const statuses = await Promise.resolve(['processing', 'cancelled']);
  statuses.forEach((status) => {
    cube(`async_${status}_orders`, {
      title: `Async ${status} orders`,
      description: 'Generated by asyncModule.',
      sql: `SELECT * FROM shop.orders WHERE status = '${status}'`,
      dimensions: {
        id: { sql: 'id', type: 'number', primaryKey: true, public: true },
      },
      measures: {
        count: { type: 'count', description: `Orders with status ${status}.` },
        revenue: { sql: 'amount', type: 'sum', description: `Revenue with status ${status}.` },
      },
    });
  });
});
